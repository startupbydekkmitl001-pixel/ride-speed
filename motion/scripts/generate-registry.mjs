import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { assets, roles } from '../src/catalog.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const media = path.resolve(root, '../ExpoRideSpeed/assets/motion/v5');
const manifest = JSON.parse(fs.readFileSync(path.join(media, 'manifest.json'), 'utf8'));
assert.equal(manifest.complete, true, 'Registry may only reference the complete verified family');
assert.equal(Object.keys(manifest.assets).length, assets.length);
const hash = file => createHash('sha256').update(fs.readFileSync(file)).digest('hex');
for (const asset of assets) {
  const record = manifest.assets[asset.id];
  assert.equal(hash(path.join(media, record.video)), record.videoSha256);
  assert.equal(hash(path.join(media, record.poster)), record.posterSha256);
}
const source = `/** Generated by motion/scripts/generate-registry.mjs from the verified family. */\n` +
  `export const motionRoles = ${JSON.stringify(roles.map(role => role.id), null, 2)} as const;\n` +
  `export type MotionRole = (typeof motionRoles)[number];\nexport type MotionTheme = "dark" | "light";\n\n` +
  `const themedAssets = {\n${assets.map(asset => `  "${asset.id}": {\n    video: require("../../../assets/motion/v5/${asset.id}.mp4") as number,\n    poster: require("../../../assets/motion/v5/${asset.id}-poster.jpg") as number,\n  },`).join('\n')}\n} as const;\n\n` +
  `/** Metro receives explicit static requires; the compatibility alias adds no media. */\nexport const ambientAssets = {\n  ...themedAssets,\n  "garage-scooter": themedAssets["garage-scooter-dark"],\n} as const;\n\nexport type AmbientAsset = keyof typeof ambientAssets;\n\n` +
  `export const motionRoleAssets = {\n${roles.map(role => `  "${role.id}": { dark: "${role.id}-dark", light: "${role.id}-light" },`).join('\n')}\n} as const satisfies Record<MotionRole, Record<MotionTheme, AmbientAsset>>;\n\n` +
  `/** The caller supplies the actual resolved app theme; no hidden system observer. */\nexport function resolveAmbientAsset(role: MotionRole, theme: MotionTheme): AmbientAsset {\n  const variants = motionRoleAssets[role];\n  if (!variants || (theme !== "dark" && theme !== "light")) {\n    throw new RangeError("Unknown motion material or theme");\n  }\n  return variants[theme];\n}\n`;
const destination = path.resolve(root, '../ExpoRideSpeed/src/features/motion/assets.ts');
fs.writeFileSync(destination, source);
console.log(`Generated ${path.relative(root, destination)} with ${assets.length} outputs and one compatibility alias`);
